function generate(raw: unknown): Uint8Array {
  const input = asCalcInput(raw);
  computeTotals(input); // Bereichsprüfung der Beträge
  return createZip(parts(input).map((p) => ({ name: p.name, bytes: new TextEncoder().encode(p.text) })), { ooxml: true });
}

/** Zellen eines Blatts lesen: Bezug → Formel, Wert, Zeichenkette. */
export function readCells(sheet: string): Map<string, { f?: string; v?: string; s?: string }> {
  const out = new Map<string, { f?: string; v?: string; s?: string }>();
  const un = (s: string): string => s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&amp;/g, '&');
  for (const m of sheet.matchAll(/<c r="([A-Z]+\d+)"[^>]*?(?:\/>|>([\s\S]*?)<\/c>)/g)) {
    const body = m[2] ?? '';
    const f = /<f>([\s\S]*?)<\/f>/.exec(body)?.[1];
    const v = /<v>([\s\S]*?)<\/v>/.exec(body)?.[1];
    const s = /<is><t[^>]*>([\s\S]*?)<\/t><\/is>/.exec(body)?.[1];
    out.set(m[1] as string, { ...(f !== undefined ? { f: un(f) } : {}), ...(v !== undefined ? { v } : {}), ...(s !== undefined ? { s: un(s) } : {}) });
  }
  return out;
}

const toMinor = (v: string | undefined, factor: number): number => Math.round(Number(v ?? 'NaN') * factor);

function runQa(bytes: Uint8Array, raw: unknown): QaCheckResult[] {
  let input: CalcInput;
  try {
    input = asCalcInput(raw);
  } catch (e) {
    return [{ check: 'input', passed: false, detail: (e as Error).message }];
  }
  let entries: ReturnType<typeof readZip>;
  try {
    entries = readZip(bytes);
  } catch (e) {
    return [{ check: 'xlsx_structure', passed: false, detail: (e as Error).message }];
  }
  const names = entries.map((x) => x.name);
  const text = (n: string): string => new TextDecoder().decode(entries.find((x) => x.name === n)?.bytes ?? new Uint8Array());
  const wellFormed = entries.every((x) => { const s = new TextDecoder().decode(x.bytes); return s.startsWith('<?xml') && !/<!DOCTYPE|<!ENTITY/i.test(s); });
  const structureOk = names.join('|') === XLSX_FILES.join('|') && entries.every((x) => x.crcOk) && wellFormed && names[0] === '[Content_Types].xml'
    && !names.some((n) => /vbaProject|\.bin$|externalLink|activeX|embeddings/i.test(n)) && text('xl/workbook.xml').includes('fullCalcOnLoad="1"');
  const results: QaCheckResult[] = [{ check: 'xlsx_structure', passed: structureOk, detail: structureOk ? `${names.length} Teile, CRC32 geprüft, keine Makros oder externen Verweise` : `Aufbau weicht ab: ${names.join(', ').slice(0, 160)}` }];

  const L = layout(input);
  const cells = readCells(text('xl/worksheets/sheet1.xml'));
  const expectedF = formulas(input);
  const allF = [...cells].filter(([, c]) => c.f !== undefined);
  const wrong = [...expectedF].filter(([ref, f]) => cells.get(ref)?.f !== f).map(([ref]) => ref);
  const extra = allF.filter(([ref]) => !expectedF.has(ref)).map(([ref]) => ref);
  results.push({ check: 'xlsx_formulas', passed: wrong.length === 0 && extra.length === 0, detail: wrong.length || extra.length ? `Formeln fehlen/weichen ab: ${[...wrong, ...extra].slice(0, 8).join(', ')}` : `${expectedF.size} Formeln (Zeilensummen, Zwischensumme, Aufschlag, Gesamt)` });

  // Inhalt wie bestellt
  const contentProblems: string[] = [];
  if (cells.get('A1')?.s !== input.title || cells.get('D1')?.s !== input.currency) contentProblems.push('Titel/Währung');
  input.items.forEach((it, i) => {
    const r = L.first + i;
    if (cells.get(`A${r}`)?.s !== it.name || Number(cells.get(`B${r}`)?.v) !== it.quantity || toMinor(cells.get(`C${r}`)?.v, L.factor) !== it.unit_cost_minor) contentProblems.push(`Zeile ${r}`);
  });
  if (Math.round(Number(cells.get(`C${L.markup}`)?.v) * 100) !== input.margin_bps) contentProblems.push('Aufschlag');
  results.push({ check: 'format', passed: contentProblems.length === 0, detail: contentProblems.length ? contentProblems.slice(0, 6).join(', ') : `${input.items.length} Positionen, Titel, Währung und Aufschlag wie bestellt` });

  // Summen: die TATSÄCHLICHEN Formeln der Datei mit der eigenen Rechenmaschine auswerten (services/product-factory/src/sheet-eval.ts)
  // und gegen die gespeicherten Ergebnisse sowie die unabhängige Fachberechnung prüfen.
  const t = computeTotals(input);
  let totalsOk: boolean;
  try {
    const ev = evaluateSheet(cells);
    const m = (ref: string): number => Math.round((ev.get(ref) ?? Number.NaN) * L.factor);
    totalsOk = [...ev.keys()].every((ref) => m(ref) === toMinor(cells.get(ref)?.v, L.factor))
      && input.items.every((_, i) => m(`D${L.first + i}`) === t.lines[i])
      && m(`D${L.subtotal}`) === t.subtotal && m(`D${L.markup}`) === t.markup && m(`D${L.total}`) === t.total;
  } catch {
    totalsOk = false;
  }
  results.push({ check: 'totals', passed: totalsOk, detail: totalsOk ? 'Formeln der Datei ausgewertet: Ergebnisse stimmen mit gespeicherten Werten und der Fachberechnung überein' : 'Formeln ergeben nicht die erwarteten Summen' });

  // Kundentexte stehen nie in Formeln; Formeln enthalten nur Zellbezüge, Zahlen und drei feste Funktionen
  const safe = /^(?:ROUND|ROUNDUP|SUM|[A-D]\d+|\d+|[():,*/+])+$/;
  const unsafe = allF.filter(([, c]) => !safe.test(c.f ?? '')).map(([ref]) => ref);
  const validations = (text('xl/worksheets/sheet1.xml').match(/<dataValidation /g) ?? []).length;
  results.push({ check: 'formula_injection', passed: unsafe.length === 0 && validations === 3, detail: unsafe.length ? `unsichere Formeln: ${unsafe.join(', ')}` : 'Formeln nur aus Zellbezügen und festen Funktionen; Kundentexte als Zeichenketten; 3 Eingabeprüfungen' });
  return results;
}

