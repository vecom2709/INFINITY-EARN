/** XML-sichere Zeichenkette (ohne Steuerzeichen, die in XML 1.0 verboten sind). */
export function xmlText(s: string): string {
  return [...s].filter((ch) => { const c = ch.codePointAt(0) ?? 0; return c === 9 || c === 10 || c === 13 || (c >= 0x20 && c !== 0xfffe && c !== 0xffff); }).join('')
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

interface Layout { first: number; last: number; subtotal: number; markup: number; total: number; hint: number; footer: number; factor: number; decimals: number }
export function layout(input: CalcInput): Layout {
  const n = input.items.length;
  const decimals = minorUnits(input.currency);
  return { first: 3, last: n + 2, subtotal: n + 3, markup: n + 4, total: n + 5, hint: n + 7, footer: n + 8, factor: 10 ** decimals, decimals };
}

/** Die Formeln der Mappe – eine Stelle für Erzeugung UND Prüfung. Rechnen in ganzen Kleinstbeträgen (keine Gleitkomma-Fehler). */
export function formulas(input: CalcInput): Map<string, string> {
  const L = layout(input);
  const f = new Map<string, string>();
  for (let r = L.first; r <= L.last; r++) f.set(`D${r}`, `ROUND(B${r}*C${r},${L.decimals})`);
  f.set(`D${L.subtotal}`, `SUM(D${L.first}:D${L.last})`);
  f.set(`D${L.markup}`, `ROUNDUP(ROUND(D${L.subtotal}*${L.factor},0)*ROUND(C${L.markup}*100,0)/10000,0)/${L.factor}`);
  f.set(`D${L.total}`, `D${L.subtotal}+D${L.markup}`);
  return f;
}

const major = (minor: number, factor: number): string => {
  const neg = minor < 0;
  const a = Math.abs(minor);
  const d = String(factor).length - 1;
  const s = `${Math.floor(a / factor)}${d ? `.${String(a % factor).padStart(d, '0')}` : ''}`;
  return neg ? `-${s}` : s;
};

function sheetXml(input: CalcInput): string {
  const L = layout(input);
  const l = LABELS[input.language];
  const t = computeTotals(input);
  const tx = TEXT[input.language];
  const f = formulas(input);
  const str = (ref: string, v: string, s = 0): string => `<c r="${ref}" s="${s}" t="inlineStr"><is><t xml:space="preserve">${xmlText(v)}</t></is></c>`;
  const num = (ref: string, v: string, s: number): string => `<c r="${ref}" s="${s}"><v>${v}</v></c>`;
  const fx = (ref: string, cached: number, s: number): string => `<c r="${ref}" s="${s}"><f>${f.get(ref)}</f><v>${major(cached, L.factor)}</v></c>`;
  const rows: string[] = [];
  rows.push(`<row r="1" ht="24" customHeight="1">${str('A1', input.title, 1)}${str('D1', input.currency, 1)}</row>`);
  rows.push(`<row r="2">${str('A2', l.pos, 2)}${str('B2', l.qty, 2)}${str('C2', l.unit, 2)}${str('D2', l.sum, 2)}</row>`);
  input.items.forEach((it, i) => {
    const r = L.first + i;
    rows.push(`<row r="${r}">${str(`A${r}`, it.name)}${num(`B${r}`, String(it.quantity), 3)}${num(`C${r}`, major(it.unit_cost_minor, L.factor), 4)}${fx(`D${r}`, t.lines[i] as number, 4)}</row>`);
  });
  rows.push(`<row r="${L.subtotal}">${str(`A${L.subtotal}`, l.subtotal, 5)}${fx(`D${L.subtotal}`, t.subtotal, 6)}</row>`);
  rows.push(`<row r="${L.markup}">${str(`A${L.markup}`, l.margin)}${str(`B${L.markup}`, tx.rate)}${num(`C${L.markup}`, (input.margin_bps / 100).toFixed(2), 7)}${fx(`D${L.markup}`, t.markup, 4)}</row>`);
  rows.push(`<row r="${L.total}">${str(`A${L.total}`, l.total, 5)}${fx(`D${L.total}`, t.total, 6)}</row>`);
  rows.push(`<row r="${L.hint}">${str(`A${L.hint}`, tx.hint, 8)}</row>`);
  rows.push(`<row r="${L.footer}">${str(`A${L.footer}`, tx.footer, 8)}</row>`);
  const dv = (type: string, sqref: string, f1: string, msg: string, f2?: string): string =>
    `<dataValidation type="${type}" operator="${f2 ? 'between' : 'greaterThanOrEqual'}" allowBlank="0" showErrorMessage="1" errorTitle="${xmlText(tx.errT)}" error="${xmlText(msg)}" sqref="${sqref}"><formula1>${f1}</formula1>${f2 ? `<formula2>${f2}</formula2>` : ''}</dataValidation>`;
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><dimension ref="A1:D${L.footer}"/><sheetViews><sheetView workbookViewId="0"><pane ySplit="2" topLeftCell="A3" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews><sheetFormatPr defaultRowHeight="15"/><cols><col min="1" max="1" width="46" customWidth="1"/><col min="2" max="2" width="16" customWidth="1"/><col min="3" max="4" width="18" customWidth="1"/></cols><sheetData>${rows.join('')}</sheetData><dataValidations count="3">${dv('whole', `B${L.first}:B${L.last}`, '0', tx.errQ)}${dv('decimal', `C${L.first}:C${L.last}`, '0', tx.errP)}${dv('decimal', `C${L.markup}`, '0', tx.errR, '90')}</dataValidations><pageMargins left="0.7" right="0.7" top="0.75" bottom="0.75" header="0.3" footer="0.3"/><pageSetup paperSize="9" orientation="portrait" fitToHeight="0"/></worksheet>`;
}

