/**
 * Zweite Produktart (15.0-M2): Kalkulation als druckfertiges PDF aus denselben Positionsdaten wie die CSV.
 * Deterministisch, ohne KI, ohne Fremd-Assets oder Fonts (Standard-Helvetica), kostenlos herstellbar.
 * Gleiche Eingabe → byte-identisches PDF: Der Erstellungszeitpunkt im PDF ist bewusst konstant,
 * damit die Prüfsumme reproduzierbar ist. Freigabe zum Verkauf nur über die Policy (ALLOWED_CAPABILITIES).
 */
const L = {
  de: { pos: 'Position', subtotal: 'Zwischensumme', margin: 'Aufschlag', total: 'Gesamt', note: 'Alle Beträge netto, ohne Umsatzsteuer.', footer: 'Erstellt mit INFINITY EARN b2b-calc-pdf v1' },
  en: { pos: 'Item', subtotal: 'Subtotal', margin: 'Markup', total: 'Total', note: 'All amounts net, excluding VAT.', footer: 'Generated by INFINITY EARN b2b-calc-pdf v1' },
  it: { pos: 'Voce', subtotal: 'Subtotale', margin: 'Ricarico', total: 'Totale', note: 'Tutti gli importi sono netti, IVA esclusa.', footer: 'Generato da INFINITY EARN b2b-calc-pdf v1' },
} as const;

const FIXED_DATE = new Date('2026-01-01T00:00:00.000Z');
export const MAX_PAGES = 20;

const money = (minor: number, c: string): string => `${formatMinor(minor, c)} ${c}`;

/** Zeilen-Marker je Position – Grundlage für die Vollständigkeitsprüfung. */
export const itemMarker = (idx: number): string => `${String(idx + 1).padStart(3, '0')})`;

export function calcPdfLines(input: CalcInput): PdfLine[] {
  const l = L[input.language];
  const t = computeTotals(input);
  return [
    { text: input.title, bold: true, size: 15, gap: 8 },
    ...input.items.map((it, i) => ({ text: `${itemMarker(i)} ${it.name} – ${it.quantity} × ${money(it.unit_cost_minor, input.currency)} = ${money(t.lines[i] as number, input.currency)}` })),
    { text: '', gap: 6 },
    { text: `${l.subtotal}: ${money(t.subtotal, input.currency)}` },
    { text: `${l.margin} (${(input.margin_bps / 100).toFixed(2)} %): ${money(t.markup, input.currency)}` },
    { text: `${l.total}: ${money(t.total, input.currency)}`, bold: true, size: 13, gap: 10 },
    { text: l.note, size: 9 },
  ];
}

function generate(raw: unknown): Uint8Array {
  const input = asCalcInput(raw);
  return createTextPdf({ title: input.title, lines: calcPdfLines(input), footer: L[input.language].footer, created: FIXED_DATE });
}

/** Strukturprüfung: Kopf, Ende, xref-Offsets zeigen exakt auf ihre Objekte, Stream-Längen stimmen. */
export function checkPdfStructure(s: string): { ok: boolean; detail: string; pages: number } {
  if (!s.startsWith('%PDF-1.4\n')) return { ok: false, detail: 'Kopfzeile fehlt', pages: 0 };
  if (!s.trimEnd().endsWith('%%EOF')) return { ok: false, detail: '%%EOF fehlt', pages: 0 };
  const xrefAt = Number(/startxref\n(\d+)/.exec(s)?.[1] ?? -1);
  if (xrefAt < 0 || s.slice(xrefAt, xrefAt + 4) !== 'xref') return { ok: false, detail: 'startxref zeigt nicht auf xref', pages: 0 };
  const offsets = [...s.slice(xrefAt).matchAll(/^(\d{10}) 00000 n $/gm)].map((m) => Number(m[1]));
  for (const [i, off] of offsets.entries()) if (s.slice(off, off + `${i + 1} 0 obj`.length) !== `${i + 1} 0 obj`) return { ok: false, detail: `Objekt ${i + 1}: Offset falsch`, pages: 0 };
  for (const m of s.matchAll(/<< \/Length (\d+) >>\nstream\n/g)) {
    const start = (m.index ?? 0) + m[0].length;
    if (s.slice(start + Number(m[1]), start + Number(m[1]) + 10) !== '\nendstream') return { ok: false, detail: 'Stream-Länge falsch', pages: 0 };
  }
  const pages = Number(/\/Type \/Pages \/Kids \[[^\]]*\] \/Count (\d+)/.exec(s)?.[1] ?? /\/Count (\d+)/.exec(s)?.[1] ?? 0);
  return { ok: offsets.length > 0, detail: `${offsets.length} Objekte, ${pages} Seite(n)`, pages };
}

function runQa(bytes: Uint8Array, raw: unknown): QaCheckResult[] {
  const results: QaCheckResult[] = [];
  const ascii = bytes.every((b) => b < 0x80);
  results.push({ check: 'encoding', passed: ascii, detail: ascii ? 'reines ASCII (WinAnsi-Escapes)' : 'unerwartete Bytes' });
  let input: CalcInput;
  try {
    input = asCalcInput(raw);
  } catch (e) {
    return [...results, { check: 'input', passed: false, detail: (e as Error).message }];
  }
  const s = new TextDecoder('latin1').decode(bytes);
  const st = checkPdfStructure(s);
  results.push({ check: 'pdf_structure', passed: st.ok, detail: st.detail });
  results.push({ check: 'pages', passed: st.pages >= 1 && st.pages <= MAX_PAGES, detail: `${st.pages} von max. ${MAX_PAGES}` });
  const missing = input.items.map((_, i) => i).filter((i) => !s.includes(pdfString(itemMarker(i))));
  results.push({ check: 'items_complete', passed: missing.length === 0, detail: missing.length ? `${missing.length} Position(en) fehlen` : `${input.items.length} Positionen` });
  const t = computeTotals(input);
  const totalText = pdfString(`${L[input.language].total}: ${money(t.total, input.currency)}`);
  results.push({ check: 'totals', passed: s.includes(totalText), detail: s.includes(totalText) ? 'Summe nachgerechnet' : 'Summe fehlt oder falsch' });
  // Gestaltung: Titel als Überschrift, Netto-Hinweis und Herkunftsfußzeile müssen sichtbar gesetzt sein.
  const l = L[input.language];
  const layout = [['Titel', pdfString(input.title)], ['Netto-Hinweis', pdfString(l.note)], ['Fußzeile', pdfString(l.footer)]].filter(([, needle]) => !s.includes(needle as string)).map(([name]) => name);
  results.push({ check: 'layout', passed: layout.length === 0, detail: layout.length ? `fehlt: ${layout.join(', ')}` : 'Titel, Netto-Hinweis und Fußzeile gesetzt' });
  return results;
}

