  data_privacy: 'Enthält nur vom Kunden gelieferte Positionsnamen/Beträge; keine personenbezogenen Daten erforderlich.',
  artifact_storage: 'Lokales Dateisystem pro Auftrag, SHA-256 geprüft.',
