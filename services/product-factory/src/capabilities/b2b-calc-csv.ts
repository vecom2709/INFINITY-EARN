import { formatMinor, minorUnits } from '../../../../packages/contracts/src/money.ts';
import { validate, type JsonSchema } from '../../../../packages/contracts/src/schemas.ts';
import { isFormulaCell, parseCsv, toCsv } from '../csv.ts';
import type { ProductCapability, QaCheckResult } from '../types.ts';

/**
 * Erster standardisierter Produktions-Use-Case: B2B-Kalkulationstabelle (CSV) aus strukturierten
 * Positionen. Rein deterministisch, ohne KI, ohne Fremd-Assets, kostenlos herstellbar.
 */
export interface CalcItem {
  name: string;
  quantity: number;
  unit_cost_minor: number;
}

export interface CalcInput {
  title: string;
  currency: string;
  items: CalcItem[];
  margin_bps: number;
  language: 'de' | 'en' | 'it';
}

export const calcInputSchema: JsonSchema = {
  type: 'object',
  required: ['title', 'currency', 'items', 'margin_bps', 'language'],
  properties: {
    title: { type: 'string', minLength: 1, maxLength: 200 },
    currency: { type: 'string', pattern: '^[A-Z]{3}$' },
    items: {
      type: 'array',
      minItems: 1,
      items: {
        type: 'object',
        required: ['name', 'quantity', 'unit_cost_minor'],
        properties: {
          name: { type: 'string', minLength: 1, maxLength: 200 },
          quantity: { type: 'integer', minimum: 1, maximum: 1000000 },
          unit_cost_minor: { type: 'integer', minimum: 0, maximum: 100000000 },
        },
      },
    },
    margin_bps: { type: 'integer', minimum: 0, maximum: 9000 },
    language: { enum: ['de', 'en', 'it'] },
  },
};

export const LABELS = {
  de: { pos: 'Position', qty: 'Menge', unit: 'Einzelpreis', sum: 'Summe', subtotal: 'Zwischensumme', margin: 'Aufschlag', total: 'Gesamt', footer: 'Erstellt mit INFINITY EARN b2b-calc-csv v1' },
  en: { pos: 'Item', qty: 'Quantity', unit: 'Unit price', sum: 'Line total', subtotal: 'Subtotal', margin: 'Markup', total: 'Total', footer: 'Generated by INFINITY EARN b2b-calc-csv v1' },
  it: { pos: 'Voce', qty: 'Quantità', unit: 'Prezzo unitario', sum: 'Totale riga', subtotal: 'Subtotale', margin: 'Ricarico', total: 'Totale', footer: 'Generato da INFINITY EARN b2b-calc-csv v1' },
} as const;

export const MAX_ITEMS = 200;

export function asCalcInput(input: unknown): CalcInput {
  const errors = validate(calcInputSchema, input);
  if (errors.length > 0) throw new Error(`INVALID_INPUT: ${errors.join('; ')}`);
  const i = input as CalcInput;
  minorUnits(i.currency);
  return i;
}

export function computeTotals(input: CalcInput): { lines: number[]; subtotal: number; markup: number; total: number } {
  const lines = input.items.map((it) => {
    const v = it.quantity * it.unit_cost_minor;
    if (!Number.isSafeInteger(v)) throw new Error('AMOUNT_OUT_OF_RANGE');
    return v;
  });
  const subtotal = lines.reduce((a, b) => a + b, 0);
  if (!Number.isSafeInteger(subtotal)) throw new Error('AMOUNT_OUT_OF_RANGE');
  const markup = Number((BigInt(subtotal) * BigInt(input.margin_bps) + 9999n) / 10000n);
  return { lines, subtotal, markup, total: subtotal + markup };
}

function headerRow(lang: CalcInput['language']): string[] {
  const l = LABELS[lang];
  return [l.pos, l.qty, l.unit, l.sum];
}

function generate(raw: unknown): Uint8Array {
  const input = asCalcInput(raw);
  const l = LABELS[input.language];
  const t = computeTotals(input);
  const fmt = (m: number): string => formatMinor(m, input.currency);
  const rows: (string | number)[][] = [
    [input.title, '', '', input.currency],
    headerRow(input.language),
    ...input.items.map((it, idx) => [it.name, it.quantity, fmt(it.unit_cost_minor), fmt(t.lines[idx] as number)]),
    [l.subtotal, '', '', fmt(t.subtotal)],
    [`${l.margin} (${(input.margin_bps / 100).toFixed(2)}%)`, '', '', fmt(t.markup)],
    [l.total, '', '', fmt(t.total)],
    [l.footer, '', '', ''],
  ];
  return new TextEncoder().encode(toCsv(rows));
}

function runQa(bytes: Uint8Array, raw: unknown): QaCheckResult[] {
  const results: QaCheckResult[] = [];
  let text: string;
  try {
    text = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
    const binary = text.includes('\u0000');
    results.push({ check: 'encoding', passed: !binary, detail: binary ? 'NUL-Byte gefunden' : 'UTF-8' });
  } catch {
    results.push({ check: 'encoding', passed: false, detail: 'kein gültiges UTF-8' });
    return [...results, { check: 'format', passed: false, detail: 'nicht dekodierbar' }];
  }
  let input: CalcInput;
  try {
    input = asCalcInput(raw);
  } catch (e) {
    return [...results, { check: 'input', passed: false, detail: (e as Error).message }];
  }
  let rows: string[][];
  try {
    rows = parseCsv(text);
  } catch (e) {
    return [...results, { check: 'format', passed: false, detail: (e as Error).message }];
  }
  const expectedRows = input.items.length + 6;
  const header = rows[1] ?? [];
  const formatOk = rows.length === expectedRows && rows.every((r) => r.length === 4) && header.join('|') === headerRow(input.language).join('|');
  results.push({ check: 'format', passed: formatOk, detail: formatOk ? `${rows.length} Zeilen` : 'Struktur/Kopfzeile weicht ab' });

  const t = computeTotals(input);
  const totalCell = rows[rows.length - 2]?.[3];
  const totalsOk = formatOk && totalCell === formatMinor(t.total, input.currency);
  results.push({ check: 'totals', passed: totalsOk, detail: totalsOk ? 'Summen nachgerechnet' : 'Summen stimmen nicht' });

  const injected = rows.flat().filter(isFormulaCell);
  results.push({ check: 'formula_injection', passed: injected.length === 0, detail: injected.length ? `${injected.length} gefährliche Zellen` : 'keine' });
  return results;
}

